// Turns the SQL that `drizzle-kit generate` wrote to ./drizzle into src/migrations.generated.ts (ADR 72),
// so the migrator reads statements from code and not from a folder (there is none inside the SEA).
// Usage: node packages/db/scripts/embed-migrations.mjs [--check]
// Migration id = (journal idx + 1) padded to 4 digits + the drizzle tag without its own number: 0000_library_scan -> 0001_library_scan.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const journal = JSON.parse(readFileSync(join(root, "drizzle/meta/_journal.json"), "utf8"));
const entries = journal.entries.map((e) => {
  const sql = readFileSync(join(root, "drizzle", `${e.tag}.sql`), "utf8").replace(/\r\n/g, "\n");
  const statements = sql
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  const id = `${String(e.idx + 1).padStart(4, "0")}${e.tag.slice(4)}`;
  return { id, statements };
});
const out =
  "// GENERATED by scripts/embed-migrations.mjs from ./drizzle. Do not edit by hand.\n" +
  "export interface EmbeddedMigration {\n  readonly id: string;\n  readonly statements: readonly string[];\n}\n\n" +
  `export const MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(entries, null, 2)};\n`;
const target = join(root, "src/migrations.generated.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) {
    console.error("migrations.generated.ts is out of date");
    process.exit(1);
  }
} else writeFileSync(target, out);
